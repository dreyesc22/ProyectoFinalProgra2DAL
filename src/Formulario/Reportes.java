    private void btnReporteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnReporteActionPerformed
        String ruta = obtenerRutaReporte();
    if (ruta == null) {
        JOptionPane.showMessageDialog(this,
            "Seleccione un reporte antes de continuar.",
            "Aviso", JOptionPane.WARNING_MESSAGE);
        return;
    }

    try {
        Map<String, Object> params = new HashMap<>();
        JasperPrint print = JasperFillManager.fillReport(ruta, params, con);
        JasperViewer.viewReport(print, false);
    } catch (JRException ex) {
        JOptionPane.showMessageDialog(this,
            "Error al visualizar el reporte:\n" + ex.getMessage(),
            "Error", JOptionPane.ERROR_MESSAGE);
        ex.printStackTrace();
    }
    }//GEN-LAST:event_btnReporteActionPerformed

    private void btnPDFActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnPDFActionPerformed
        String ruta = obtenerRutaReporte();
    if (ruta == null) {
        JOptionPane.showMessageDialog(this,
            "Seleccione un reporte antes de imprimir.",
            "Aviso", JOptionPane.WARNING_MESSAGE);
        return;
    }

    try {
        JasperPrint print = JasperFillManager.fillReport(ruta, null, con);
        JasperPrintManager.getInstance(DefaultJasperReportsContext.getInstance())
                .print(print, true);
        JOptionPane.showMessageDialog(this,
            "El reporte se envió correctamente a la impresora o PDF virtual.",
            "Éxito", JOptionPane.INFORMATION_MESSAGE);
    } catch (JRException ex) {
        JOptionPane.showMessageDialog(this,
            "Error al imprimir el reporte:\n" + ex.getMessage(),
            "Error", JOptionPane.ERROR_MESSAGE);
        ex.printStackTrace();
    }
    }//GEN-LAST:event_btnPDFActionPerformed


