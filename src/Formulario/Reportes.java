    private String obtenerRutaReporte() {
    String rutaBase = "src/reportes/";

    if (RBEmpleados.isSelected()) {
        return rutaBase + "empleados.jasper";
    } else if (RBProveedores.isSelected()) {
        return rutaBase + "proveedores.jasper";
    } else if (RBClientes.isSelected()) {
        return rutaBase + "clientes.jasper";
    } else if (RBProductos.isSelected()) {
        return rutaBase + "productos.jasper";
    } else if (RBVentasGenerales.isSelected()) {
        return rutaBase + "ventasGenerales.jasper";
    } else if (RBVentasProductos.isSelected()) {
        return rutaBase + "ventasProductos.jasper";
    }

    return null;
}



